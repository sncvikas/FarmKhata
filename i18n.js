let currentLang = localStorage.getItem('fk_lang') || 'en';

function t(key) {
  return (I18N[currentLang] && I18N[currentLang][key]) || I18N.en[key] || key;
}

function applyI18n() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = t(el.getAttribute('data-i18n'));
  });
  document.getElementById('langBtn').textContent = currentLang === 'en' ? 'ಕನ್ನಡ' : 'English';
}

function toggleLang() {
  currentLang = currentLang === 'en' ? 'kn' : 'en';
  localStorage.setItem('fk_lang', currentLang);
  applyI18n();
  if (typeof renderCurrentScreen === 'function') renderCurrentScreen();
}
